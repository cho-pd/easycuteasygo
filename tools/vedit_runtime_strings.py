"""VEDIT: names that are translated at run time (package JSON labels, preset tables) are invisible
to lupdate, which then drops their translations from i18n/drift_ko.ts as obsolete on every build.

This keeps them alive:
  * writes src/vedit/VeditRuntimeStrings.cpp — QT_TRANSLATE_NOOP marks for every source string, so
    lupdate sees them;
  * adds any missing <message> (with its Korean translation) to i18n/drift_ko.ts.

The table is tools/vedit_runtime_strings.json ({context: {english: korean}}). Re-run after adding a
package or preset:

    python tools/vedit_runtime_strings.py
"""
import json
import os
import re

APP = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
TABLE = os.path.join(APP, 'tools', 'vedit_runtime_strings.json')
CPP = os.path.join(APP, 'src', 'vedit', 'VeditRuntimeStrings.cpp')
TS = os.path.join(APP, 'i18n', 'drift_ko.ts')


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def xml(s):
    return s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def main():
    data = json.load(open(TABLE, encoding='utf-8'))

    os.makedirs(os.path.dirname(CPP), exist_ok=True)
    lines = ['// VEDIT: generated by tools/vedit_runtime_strings.py — do not edit by hand.',
             '// Run-time-translated names (package labels, preset tables) marked for lupdate so their',
             '// Korean translations survive the catalogue update on every build.',
             '#include <QtGlobal>', '', 'namespace {', '',
             '[[maybe_unused]] const char *const kVeditRuntimeStrings[] = {']
    for ctx, table in data.items():
        for src in table:
            lines.append(f'    QT_TRANSLATE_NOOP({cstr(ctx)}, {cstr(src)}),')
    lines += ['};', '', '} // namespace', '']
    open(CPP, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))

    ts = open(TS, encoding='utf-8').read()
    added = 0
    for ctx, table in data.items():
        head = f'    <name>{xml(ctx)}</name>\n'
        if head not in ts:
            ts = ts.replace('</TS>', f'<context>\n{head}</context>\n</TS>')
        start = ts.index(head)
        end = ts.index('</context>', start)
        block = ts[start:end]
        add = ''
        for src, tr in table.items():
            if f'<source>{xml(src)}</source>' in block:
                continue
            add += (f'    <message>\n        <source>{xml(src)}</source>\n'
                    f'        <translation>{xml(tr)}</translation>\n    </message>\n')
            added += 1
        ts = ts[:start + len(head)] + add + ts[start + len(head):]
    open(TS, 'w', encoding='utf-8', newline='').write(ts)
    print(f'wrote {CPP}; added {added} translations')


if __name__ == '__main__':
    main()
